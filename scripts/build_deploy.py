"""Assemble a deploy folder for the Dash app: only what it needs at runtime.

Usage: python scripts/build_deploy.py [OUT_DIR]   (default: build/deploy)

The folder works for:
- Plotly Cloud: drag its contents into the browser (entry app.py, requirements.txt).
- Render or any Docker host: the Dockerfile runs gunicorn dash_app:server.
"""
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build" / "deploy"

FILES = ["Dockerfile", "requirements-dash.txt", "dash_app.py", "figures.py", "pipeline/__init__.py",
         "pipeline/insights.py", "config/settings.yaml"]
DIRS = ["dashapp", "data/processed"]

README = """# Where Should the Next Teacher Go? (Dash app, deploy copy)

Decision tool ranking Nigeria's 774 LGAs by their gap to the UBE standard of 35 learners per teacher and per
classroom, with confidence grades. Built from public data (Federal Ministry of Education Annual School Census 2024
and others). Generated by scripts/build_deploy.py; source code, method and data audit: {repo}
"""

APP_PY = '''"""Entry point for hosts that look for app.py (e.g. Plotly Cloud)."""
import os

from dash_app import app, server  # noqa: F401

if __name__ == "__main__":
    app.run(host="0.0.0.0", port=int(os.environ.get("PORT", 8050)))
'''


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    for f in FILES:
        (OUT / f).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / f, OUT / f)
    for d in DIRS:
        shutil.copytree(ROOT / d, OUT / d, ignore=shutil.ignore_patterns("__pycache__", ".gitkeep"))
    # Linux containers need LF line endings in the Dockerfile, whatever the local checkout uses.
    df = OUT / "Dockerfile"
    df.write_bytes(df.read_bytes().replace(bytes([13, 10]), bytes([10])))
    repo = "https://github.com/Jagunmolu/data-candlers"
    (OUT / "README.md").write_text(README.format(repo=repo), encoding="utf-8")
    (OUT / "app.py").write_text(APP_PY, encoding="utf-8")
    shutil.copy2(ROOT / "requirements-dash.txt", OUT / "requirements.txt")
    size = sum(p.stat().st_size for p in OUT.rglob("*") if p.is_file()) / 1e6
    print(f"Deploy folder ready: {OUT} ({size:.1f} MB)")


if __name__ == "__main__":
    main()
